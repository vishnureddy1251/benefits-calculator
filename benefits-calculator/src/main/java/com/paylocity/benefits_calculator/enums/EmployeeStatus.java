package com.paylocity.benefits_calculator.enums;

/**
 * Enum representing the status of an employee.
 *
 * @author Benefits Calculator Team
 * @version 1.0
 */
public enum EmployeeStatus {
    /**
     * Employee is pending activation
     */
    PENDING,

    /**
     * Employee is currently active
     */
    ACTIVE,

    /**
     * Employee is no longer active (soft delete)
     */
    INACTIVE
}


















